<?php

header("Content-Type: application/json; charset=UTF-8");

/*
|--------------------------------------------------------------------------
| TELEGRAM
|--------------------------------------------------------------------------
|
| ВСТАВЬ СЮДА НОВЫЙ ТОКЕН,
| который получишь через @BotFather.
|
*/

$botToken = "8983993848:AAEfFggQV6tfGt8dp-3WdNbyGKDewYzvKnk";

$chatId = "919523071";


/*
|--------------------------------------------------------------------------
| Получаем данные от сайта
|--------------------------------------------------------------------------
*/

$rawData = file_get_contents("php://input");

$data = json_decode($rawData, true);


if (!$data) {

    http_response_code(400);

    echo json_encode([
        "success" => false,
        "error" => "Не удалось получить данные"
    ]);

    exit;
}


/*
|--------------------------------------------------------------------------
| Получаем ответ и время
|--------------------------------------------------------------------------
*/

$answer = $data["answer"] ?? "Ответ не указан";

$date = $data["date"] ?? date(
    "d.m.Y H:i:s"
);


/*
|--------------------------------------------------------------------------
| Защищаем текст
|--------------------------------------------------------------------------
*/

$safeAnswer = htmlspecialchars(
    $answer,
    ENT_QUOTES,
    "UTF-8"
);

$safeDate = htmlspecialchars(
    $date,
    ENT_QUOTES,
    "UTF-8"
);


/*
|--------------------------------------------------------------------------
| Формируем сообщение
|--------------------------------------------------------------------------
*/

$message =
    "💌 <b>Ответ на приглашение</b>\n\n" .
    "❤️ " . $safeAnswer . "\n" .
    "🕐 " . $safeDate;


/*
|--------------------------------------------------------------------------
| URL Telegram API
|--------------------------------------------------------------------------
*/

$url =
    "https://api.telegram.org/bot" .
    $botToken .
    "/sendMessage";


/*
|--------------------------------------------------------------------------
| Параметры запроса
|--------------------------------------------------------------------------
*/

$postFields = [

    "chat_id" =>
        $chatId,

    "text" =>
        $message,

    "parse_mode" =>
        "HTML"

];


/*
|--------------------------------------------------------------------------
| Отправка запроса
|--------------------------------------------------------------------------
*/

$ch = curl_init();


curl_setopt(
    $ch,
    CURLOPT_URL,
    $url
);


curl_setopt(
    $ch,
    CURLOPT_POST,
    true
);


curl_setopt(
    $ch,
    CURLOPT_POSTFIELDS,
    $postFields
);


curl_setopt(
    $ch,
    CURLOPT_RETURNTRANSFER,
    true
);


curl_setopt(
    $ch,
    CURLOPT_TIMEOUT,
    10
);


/*
|--------------------------------------------------------------------------
| Выполняем запрос
|--------------------------------------------------------------------------
*/

$response = curl_exec($ch);


$httpCode = curl_getinfo(
    $ch,
    CURLINFO_HTTP_CODE
);


$curlError = curl_error($ch);


curl_close($ch);


/*
|--------------------------------------------------------------------------
| Проверяем ошибку cURL
|--------------------------------------------------------------------------
*/

if ($curlError) {

    http_response_code(500);

    echo json_encode([
        "success" => false,
        "error" => "Ошибка сервера: " . $curlError
    ]);

    exit;
}


/*
|--------------------------------------------------------------------------
| Разбираем ответ Telegram
|--------------------------------------------------------------------------
*/

$result = json_decode(
    $response,
    true
);


/*
|--------------------------------------------------------------------------
| Успех
|--------------------------------------------------------------------------
*/

if (
    $httpCode >= 200 &&
    $httpCode < 300 &&
    isset($result["ok"]) &&
    $result["ok"] === true
) {

    echo json_encode([
        "success" => true
    ]);

    exit;
}


/*
|--------------------------------------------------------------------------
| Ошибка Telegram
|--------------------------------------------------------------------------
*/

http_response_code(500);

echo json_encode([

    "success" => false,

    "error" =>
        $result["description"]
        ?? "Telegram API error"

]);

?>